#!/usr/bin/python3
"""Pure iptables-save evidence. No commands, imports of UFW, or policy writes.

Only generated timestamp comments and chain packet/byte counters are excluded.
All tables, chain policies, rule bytes, and their order remain evidence.
"""
from dataclasses import dataclass
import hashlib
import re
import shlex
import time


class KernelError(ValueError):
    pass


NAME = rb'[A-Za-z0-9_.:+-]{1,255}'
CHAIN = re.compile(rb':(' + NAME + rb') (ACCEPT|DROP|QUEUE|RETURN|-) \[([0-9]{1,20}):([0-9]{1,20})\]')
GENERATED = re.compile(rb'# Generated by (?:ip6tables|iptables)-save v[0-9]+(?:\.[0-9]+){1,3}(?: \((?:nf_tables|legacy)\))? on (.+)')
COMPLETED = re.compile(rb'# Completed on (.+)')


@dataclass(frozen=True)
class KernelTable:
    name: str
    chains: tuple
    rules: tuple


@dataclass(frozen=True)
class KernelSave:
    tables: tuple

    @property
    def canonical(self):
        lines = []
        for table in self.tables:
            lines.append(b'*' + table.name.encode('ascii'))
            lines.extend(b':' + name.encode('ascii') + b' ' + policy.encode('ascii') + b' [0:0]' for name, policy in table.chains)
            lines.extend(table.rules)
            lines.append(b'COMMIT')
        return b'\n'.join(lines) + (b'\n' if lines else b'')

    @property
    def fingerprint(self):
        return hashlib.sha256(self.canonical).hexdigest()

    @classmethod
    def parse(cls, raw):
        if (not isinstance(raw, bytes) or not raw or len(raw) > 8 * 1024 * 1024
                or not raw.endswith(b'\n') or b'\r' in raw or b'\x00' in raw):
            raise KernelError('invalid kernel-save framing')
        lines = raw.splitlines()
        if len(lines) > 65536:
            raise KernelError('kernel-save line budget exceeded')
        tables, seen = [], set()
        name, chains, rules, declared = None, [], [], set()
        for line in lines:
            if line.startswith(b'#'):
                match = GENERATED.fullmatch(line) or COMPLETED.fullmatch(line)
                if name is not None or not match:
                    raise KernelError('unknown kernel-save comment')
                stamp = match.group(1)
                try:
                    decoded = stamp.decode('ascii')
                    parsed = time.strptime(decoded, '%a %b %d %H:%M:%S %Y')
                    # ctime has space-padded days; strptime alone accepts many
                    # noncanonical forms. Accept only the two ctime layouts.
                    if decoded != time.strftime('%a %b %d %H:%M:%S %Y', parsed) and decoded != time.asctime(parsed):
                        raise ValueError()
                except (UnicodeError, ValueError, OverflowError) as exc:
                    raise KernelError('invalid kernel-save timestamp') from exc
                continue
            if line.startswith(b'*'):
                candidate = line[1:]
                if name is not None or not re.fullmatch(NAME, candidate) or candidate in seen or len(tables) >= 32:
                    raise KernelError('invalid or duplicate kernel table')
                name, chains, rules, declared = candidate.decode('ascii'), [], [], set()
                seen.add(candidate)
                continue
            if line == b'COMMIT':
                if name is None or not chains:
                    raise KernelError('unexpected kernel table commit')
                tables.append(KernelTable(name, tuple(chains), tuple(rules)))
                name = None
                continue
            if name is None:
                raise KernelError('kernel-save record outside table')
            match = CHAIN.fullmatch(line)
            if match:
                chain, policy = match.group(1).decode('ascii'), match.group(2).decode('ascii')
                if rules or chain in declared:
                    raise KernelError('duplicate or late chain declaration')
                declared.add(chain)
                chains.append((chain, policy))
                continue
            if line.startswith(b'-A '):
                try:
                    tokens = shlex.split(line.decode('utf-8'), comments=False, posix=True)
                except (UnicodeError, ValueError) as exc:
                    raise KernelError('invalid kernel rule tokens') from exc
                if len(tokens) < 4 or tokens[0] != '-A' or tokens[1] not in declared:
                    raise KernelError('kernel rule has unknown chain')
                # Keep the original bytes. No match/target extension or comment
                # is omitted, reordered, normalized, or treated as a counter.
                rules.append(line)
                continue
            raise KernelError('unsupported kernel-save grammar')
        if name is not None or not tables:
            raise KernelError('incomplete kernel-save table')
        return cls(tuple(tables))


def capture_kernel(read):
    """Read both families twice. The callable must capture bytes, never log them.

    This detects observed policy races, not an adversarial root changing A→B→A
    between reads. Callers must additionally bracket raw-file/UI observations
    with this evidence and retain their normal exclusive deployment lock.
    """
    def pair():
        return tuple(KernelSave.parse(read([binary])) for binary in ('iptables-save', 'ip6tables-save'))
    before = pair()
    after = pair()
    if before != after:
        raise KernelError('kernel policy changed during capture')
    return before


# Extend only after independent actual-version calibration. Acceptance is an
# evidence format check, never authorization of a policy/backend mapping.
NATIVE_META_PROFILES = {
    'nftables-1.0.2-schema1': {'version': '1.0.2', 'release_name': 'Lester Gooch', 'json_schema_version': 1},
    'nftables-1.0.9-schema1': {'version': '1.0.9', 'release_name': 'Old Doc Yak #3', 'json_schema_version': 1},
    'nftables-1.1.6-schema1': {'version': '1.1.6', 'release_name': 'Commodore Bullmoose #7', 'json_schema_version': 1},
}


@dataclass(frozen=True)
class NativeRuleset:
    canonical: bytes

    @property
    def fingerprint(self):
        return hashlib.sha256(self.canonical).hexdigest()

    @classmethod
    def parse(cls, raw, *, profile):
        import json
        if profile not in NATIVE_META_PROFILES or not isinstance(raw, bytes) or len(raw) > 8 * 1024 * 1024:
            raise KernelError('unsupported native evidence profile or size')

        # Bound structure before materializing JSON. Brackets/separators inside
        # quoted/escaped literals are not structure and are never rewritten.
        depth = structural = 0
        quoted = escaped = False
        for byte in raw:
            if quoted:
                if escaped:
                    escaped = False
                elif byte == 92:
                    escaped = True
                elif byte == 34:
                    quoted = False
                continue
            if byte == 34:
                quoted = True
            elif byte in (123, 91):
                depth += 1
                structural += 1
                if depth > 64:
                    raise KernelError('native JSON depth budget exceeded')
            elif byte in (125, 93):
                depth -= 1
                if depth < 0:
                    raise KernelError('invalid native JSON bracket framing')
            elif byte in (44, 58):
                structural += 1
            if structural > 200000:
                raise KernelError('native JSON structure budget exceeded')
        if depth or quoted:
            raise KernelError('incomplete native JSON framing')

        def integer(text):
            if len(text) > 21:
                raise KernelError('native integer budget exceeded')
            value = int(text)
            if not -(2**63) <= value < 2**64:
                raise KernelError('native integer range exceeded')
            return value

        def noninteger(unused):
            raise KernelError('noninteger native numeric value')

        def object_pairs(pairs):
            result = {}
            for key, value in pairs:
                if key in result:
                    raise KernelError('duplicate native object key')
                result[key] = value
            return result

        try:
            value = json.loads(raw.decode('utf-8'), parse_int=integer, parse_float=noninteger,
                               parse_constant=noninteger, object_pairs_hook=object_pairs)
        except (UnicodeError, ValueError, RecursionError) as exc:
            raise KernelError('invalid native JSON evidence') from exc
        pending, count = [(value, 0)], 0
        while pending:
            item, depth = pending.pop()
            count += 1
            if depth > 64 or count > 200000:
                raise KernelError('native JSON structure budget exceeded')
            if isinstance(item, dict):
                pending.extend((x, depth + 1) for x in item.values())
            elif isinstance(item, list):
                pending.extend((x, depth + 1) for x in item)
        if not isinstance(value, dict) or set(value) != {'nftables'} or not isinstance(value['nftables'], list):
            raise KernelError('invalid native root object')
        records = value['nftables']
        if not records or len(records) > 65536 or not isinstance(records[0], dict) or set(records[0]) != {'metainfo'}:
            raise KernelError('missing native metainfo')
        meta = records[0]['metainfo']
        expected = NATIVE_META_PROFILES[profile]
        if (not isinstance(meta, dict) or set(meta) != set(expected)
                or type(meta.get('json_schema_version')) is not int
                or type(meta.get('version')) is not str or type(meta.get('release_name')) is not str
                or meta != expected):
            raise KernelError('native metainfo profile differs')

        def unsigned(number):
            if type(number) is not int or not 0 <= number < 2**64:
                raise KernelError('invalid native counter or handle')

        for index, record in enumerate(records):
            if not isinstance(record, dict) or len(record) != 1:
                raise KernelError('invalid native record framing')
            kind, body = next(iter(record.items()))
            if kind == 'metainfo':
                if index != 0:
                    raise KernelError('duplicate native metainfo')
                continue
            if kind in ('table', 'chain', 'rule'):
                if not isinstance(body, dict):
                    raise KernelError('invalid native policy object')
                if 'handle' in body:
                    unsigned(body['handle'])
                    del body['handle']
            if kind == 'rule':
                if not isinstance(body.get('expr'), list):
                    raise KernelError('invalid native rule expression sequence')
                for statement in body['expr']:
                    # This precise path is the ONLY counter normalization.
                    # No recursive key/string search or unknown-field removal.
                    if isinstance(statement, dict) and set(statement) == {'counter'}:
                        counter = statement['counter']
                        if isinstance(counter, dict) and set(counter) == {'packets', 'bytes'}:
                            unsigned(counter['packets'])
                            unsigned(counter['bytes'])
                            counter.update(packets=0, bytes=0)
            # Unknown objects and nested values remain complete evidence. A
            # separate calibrated support validator must reject unsupported
            # policy BEFORE any mutator; this parser does not authorize it.
        try:
            canonical = json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False, allow_nan=False).encode('utf-8')
        except (UnicodeError, ValueError, RecursionError) as exc:
            raise KernelError('invalid native canonical encoding') from exc
        return cls(canonical)
