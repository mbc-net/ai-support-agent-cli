META={'version':'1.1.6','release_name':'Commodore Bullmoose #7','json_schema_version':1}
PROFILE='nftables-1.1.6-schema1'
NATIVE={'nftables':[{'metainfo':META},{'table':{'family':'ip','name':'filter','handle':1}},{'chain':{'family':'ip','table':'filter','name':'INPUT','handle':2,'type':'filter','hook':'input','prio':0,'policy':'accept'}},{'rule':{'family':'ip','table':'filter','chain':'INPUT','handle':3,'expr':[{'match':{'op':'==','left':{'meta':{'key':'skuid'}},'right':1001}},{'counter':{'packets':5,'bytes':60}},{'accept':None}],'comment':'literal counter packets 1 bytes 2'}}]}

def native(value):return k.NativeRuleset.parse(json.dumps(value).encode(),profile=PROFILE)

class NativeNormalizationTests(unittest.TestCase):
 def test_only_direct_known_handles_and_anonymous_counters_ignored(self):
  other=copy.deepcopy(NATIVE)
  for row in other['nftables'][1:]:
   next(iter(row.values()))['handle']+=100
  other['nftables'][-1]['rule']['expr'][1]['counter']={'packets':900,'bytes':10000}
  self.assertEqual(native(NATIVE),native(other))
 def test_policy_literals_numbers_and_unknown_fields_preserved(self):
  variants=[]
  for path,value in [((3,'rule','comment'),'literal counter packets 999 bytes 2'),((2,'chain','prio'),-10),((2,'chain','hook'),'forward'),((2,'chain','policy'),'drop')]:
   other=copy.deepcopy(NATIVE);row=other['nftables'][path[0]][path[1]];row[path[2]]=value;variants.append(other)
  for expr in [{'match':{'op':'==','left':{'meta':{'key':'skuid'}},'right':1002}},{'map':{'data':{'counter':{'packets':8,'bytes':9}},'handle':99}},{'set':{'elem':[1,2,3]}},{'vmap':{'data':{'set':[[1,{'drop':None}]]}}}]:
   other=copy.deepcopy(NATIVE);other['nftables'][-1]['rule']['expr'][0]=expr;variants.append(other)
  for other in variants:
   with self.subTest(other=other):self.assertNotEqual(native(NATIVE),native(other))
 def test_nested_counter_handle_keys_never_removed(self):
  other=copy.deepcopy(NATIVE);other['nftables'].append({'set':{'family':'inet','table':'x','name':'literal','handle':99,'elem':[{'counter':{'packets':1,'bytes':2}}]}})
  result=native(other).canonical
  self.assertIn(b'"handle":99',result);self.assertIn(b'"packets":1',result)
 def test_list_order_preserved_object_key_order_ignored(self):
  reordered=copy.deepcopy(NATIVE);reordered['nftables'][1]['table']=dict(reversed(list(reordered['nftables'][1]['table'].items())))
  self.assertEqual(native(NATIVE),native(reordered))
  reordered['nftables'][-1]['rule']['expr'].reverse()
  self.assertNotEqual(native(NATIVE),native(reordered))
 def test_invalid_handle_and_counter_numeric_types_rejected(self):
  for bad in (True,False,-1,1.5,2**64,'9',None):
   for kind in ('table','chain','rule'):
    other=copy.deepcopy(NATIVE);next(row[kind] for row in other['nftables'] if kind in row)['handle']=bad
    with self.subTest(kind=kind,bad=bad):
     with self.assertRaises(k.KernelError):native(other)
   other=copy.deepcopy(NATIVE);other['nftables'][-1]['rule']['expr'][1]['counter']['packets']=bad
   with self.subTest(counter=bad):
    with self.assertRaises(k.KernelError):native(other)
 def test_duplicate_keys_nonfinite_and_floats_rejected(self):
  for raw in (b'{"nftables":[],"nftables":[]}',json.dumps(NATIVE).replace('1001','NaN').encode(),json.dumps(NATIVE).replace('1001','Infinity').encode(),json.dumps(NATIVE).replace('1001','1.0').encode()):
   with self.subTest(raw=raw):
    with self.assertRaises(k.KernelError):k.NativeRuleset.parse(raw,profile=PROFILE)
 def test_metainfo_must_match_fixed_profile_and_exact_numeric_type(self):
  for key,value in [('version','9.0.0'),('release_name','unknown'),('json_schema_version',True),('json_schema_version',2)]:
   other=copy.deepcopy(NATIVE);other['nftables'][0]['metainfo'][key]=value
   with self.subTest(key=key,value=value):
    with self.assertRaises(k.KernelError):native(other)
  with self.assertRaises(k.KernelError):k.NativeRuleset.parse(json.dumps(NATIVE).encode(),profile='unknown')
